"""``opera-vlm config``: generate runconfigs, algorithm parameters, schemas.

GENERATED by sas-scaffold (the `runconfig` options come from the interview
spec), then owned by this repo.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import click


@click.group(name="config")
def config_group() -> None:
    """Generate configuration files."""


def _write(model, output: Path | None, with_comments: bool = True) -> None:
    if output is None:
        model.to_yaml(sys.stdout, with_comments=with_comments)
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        model.to_yaml(output, with_comments=with_comments)
        click.echo(f"Wrote {output}", err=True)


@config_group.command("template")
@click.option(
    "-o", "--output", type=click.Path(path_type=Path), help="Default: stdout."
)
def template_cli(output: Path | None) -> None:
    """Empty, commented PGE runconfig (configs/runconfig.yaml)."""
    from opera_vlm.config import RunConfig

    _write(RunConfig.construct_empty(), output)


@config_group.command("algorithm")
@click.option(
    "--set",
    "set_",
    multiple=True,
    metavar="GROUP.OPTION=VALUE",
    help="Override a default (VALUE parsed as JSON). Repeatable.",
)
@click.option(
    "-o", "--output", type=click.Path(path_type=Path), help="Default: stdout."
)
def algorithm_cli(set_: tuple[str, ...], output: Path | None) -> None:
    """Algorithm parameters YAML with defaults (configs/algorithm_parameters.yaml)."""
    from opera_vlm.config import AlgorithmParameters
    from opera_vlm.config._utils import parse_set_option

    params = AlgorithmParameters().with_overrides(parse_set_option(set_))
    _write(params, output)


@config_group.command("schema")
@click.option(
    "--algorithm", is_flag=True, help="Schema of the algorithm parameters instead."
)
@click.option(
    "-o", "--output", type=click.Path(path_type=Path), help="Default: stdout."
)
def schema_cli(algorithm: bool, output: Path | None) -> None:
    """JSON Schema of the runconfig (for the PGE team)."""
    from opera_vlm.config import AlgorithmParameters, RunConfig

    model = AlgorithmParameters if algorithm else RunConfig
    text = json.dumps(model.model_json_schema(by_alias=True), indent=2) + "\n"
    if output is None:
        click.echo(text, nl=False)
    else:
        output.write_text(text)


