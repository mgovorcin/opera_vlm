def _iso(dt) -> str:
    from ._metadata import iso_utc

    return iso_utc(dt)


def _computed(result: "AlgorithmResult") -> dict[str, Any]:
    """Values derivable from the product layers and the job's inputs."""
    from ._georef import crs_label
    from ._layers import LAYERS

    ds = result.layers
    out: dict[str, Any] = {
        "ceos_number_of_input_granules": len(result.source_files),
        "product_pixel_coordinate_convention": "pixel center",
    }
    if result.reference_datetime is not None:
        out["source_data_earliest_acquisition"] = _iso(result.reference_datetime)
    if result.secondary_datetime is not None:
        out["source_data_latest_acquisition"] = _iso(result.secondary_datetime)
    if (
        "x" in ds.coords
        and "y" in ds.coords
        and ds.sizes["x"] > 1
        and ds.sizes["y"] > 1
    ):
        x, y = ds["x"].values, ds["y"].values
        dx, dy = float(abs(x[1] - x[0])), float(abs(y[1] - y[0]))
        out["product_sample_spacing"] = f"{dx:g}, {dy:g}"
        epsg = ds.attrs.get("epsg") or (
            ds.rio.crs.to_epsg() if hasattr(ds, "rio") and ds.rio.crs else ""
        )
        bounds = (
            x.min() - dx / 2,
            y.min() - dy / 2,
            x.max() + dx / 2,
            y.max() + dy / 2,
        )
        out["product_bounding_box"] = (
            ", ".join(f"{b:.3f}" for b in bounds) + f", EPSG:{epsg}"
        )
        if epsg:
            out["product_coordinate_reference_system"] = crs_label(int(epsg))
    main = LAYERS[0]
    if main.name in ds:
        data = np.asarray(ds[main.name].values)
        fill = main.fill_value
        nodata = (
            ~np.isfinite(data)
            if np.issubdtype(data.dtype, np.floating)
            else data == fill
        )
        out["nodata_pixel_count"] = int(np.count_nonzero(nodata))
    return out


def ceos_values(result: "AlgorithmResult") -> dict[str, dict[str, Any]]:
    """CEOS values per product group: static < computed < runtime (later wins)."""
    if not CEOS_ENABLED:
        return {"identification": {}, "metadata": {}}
    values: dict[str, Any] = {
        k: v for k, v in CEOS_STATIC.items() if v not in (None, "")
    }
    values.update(_computed(result))
    values.update(result.ceos)
    unknown = set(result.ceos) - {f.name for f in CEOS_FIELDS}
    if unknown:
        raise ValueError(
            f"AlgorithmResult.ceos has undeclared CEOS fields: {sorted(unknown)}"
        )
    grouped: dict[str, dict[str, Any]] = {"identification": {}, "metadata": {}}
    for f in CEOS_FIELDS:
        if f.name in values:
            grouped[f.group][f.name] = values[f.name]
    return grouped


def check_compliance(product: Path | str) -> list[tuple[CeosField, str]]:
    """(field, status) for every declared field; status ok|missing|placeholder.

    ``product_coordinate_reference_system`` is also checked against the file
    itself: it is ``ungridded`` unless every 2-D layer points at a
    ``spatial_ref`` grid mapping with a WKT (`georef_problems`).
    """
    import h5py

    from ._georef import georef_problems

    report = []
    with h5py.File(product, "r") as h5:
        problems = georef_problems(h5)
        for f in CEOS_FIELDS:
            key = f"{f.group}/{f.name}"
            if key not in h5:
                report.append((f, "missing"))
                continue
            value = h5[key][()]
            text = value.decode() if isinstance(value, bytes) else str(value)
            if PLACEHOLDER in text:
                report.append((f, "placeholder"))
            elif f.name == "product_coordinate_reference_system" and problems:
                report.append((f, "ungridded"))
            else:
                report.append((f, "ok"))
    return report


def is_compliant(report: list[tuple[CeosField, str]]) -> bool:
    """Return True when every required field is ok."""
    return all(status == "ok" for f, status in report if f.required)


def compliance_matrix() -> str:
    """Markdown compliance matrix (docs/ceos-compliance.md)."""
    lines = [
        "# CEOS-ARD compliance matrix",
        "",
        (
            "Generated by `opera-vlm ceos matrix` from"
            " `src/opera_vlm/product/_ceos.py`; do not edit by hand."
        ),
        "",
        (
            f"Claimed: **{'yes' if CEOS_ENABLED else 'no'}**. Product type:"
            f" `{CEOS_STATIC.get('ceos_analysis_ready_data_product_type', '')}`. PFS:"
            f" {CEOS_STATIC.get('ceos_analysis_ready_data_document_identifier', '')}"
        ),
        "",
        (
            "Source: *static* = constant in `CEOS_STATIC`; *computed* = derived from"
            " the product; *runtime* = provided by the algorithm per job."
        ),
        "",
        "| Section | Field | Group | Source | Required | Value / description |",
        "|---|---|---|---|---|---|",
    ]
    for f in CEOS_FIELDS:
        value = CEOS_STATIC.get(f.name, "") if f.source == "static" else ""
        shown = (
            f"`{value}`"
            if value not in ("", None)
            else ("**TODO**" if f.source == "static" else f.description)
        )
        lines.append(
            f"| {f.section} | `{f.name}` | {f.group} | {f.source} |"
            f" {'yes' if f.required else 'no'} | {shown} |"
        )
    return "\n".join(lines) + "\n"
