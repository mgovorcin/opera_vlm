"""Runconfig file groups: inputs, dynamic ancillaries, static ancillaries.

GENERATED by sas-scaffold from the interview spec (.sas-spec.json), then owned
by this repo: edit freely.

Conventions (OPERA SAS):
- input_file_group: the primary science inputs of one job.
- dynamic_ancillary_file_group: auxiliary inputs that change per job (DEM tile,
  troposphere/ionosphere for the job's dates, the algorithm parameters file).
- static_ancillary_file_group: versioned, job-independent databases (frame
  DB, per-frame overrides JSON, event catalogues). Delivered with the SAS and
  updated by a new dated file, never edited in place.
"""

from __future__ import annotations

from typing import List, Literal, Optional  # noqa: F401

from pydantic import Field

from ._utils import FileList, OptionalPath, RequiredPath  # noqa: F401
from ._yaml import STRICT_CONFIG_WITH_ALIASES, YamlModel


class InputFileGroup(YamlModel):
    """Primary input files of one job."""

    frame_id: int = Field(
        ...,
        ge=0,
        description="Frame ID of the products to process.",
    )

    ascending_disp_files: FileList = Field(
        default_factory=list,
        min_length=1,
        description=(
            "Ascending DISP products (DISP-S1 for VLM-S1, DISP-NISAR for VLM-NI) of "
            "the frame stack."
        ),
    )

    descending_disp_files: FileList = Field(
        default_factory=list,
        description=(
            "Descending DISP products over the same area. If absent, vertical comes "
            "from the single-geometry projection (mode 2) everywhere."
        ),
    )

    ascending_cal_files: FileList = Field(
        default_factory=list,
        min_length=1,
        description=(
            "DISP-CAL products matching each ascending DISP product (same "
            "reference/secondary dates)."
        ),
    )

    descending_cal_files: FileList = Field(
        default_factory=list,
        description=(
            "DISP-CAL products matching each descending DISP product; required when "
            "descending_disp_files is given."
        ),
    )

    unr_grid_latlon_file: OptionalPath = Field(
        default=None,
        description=(
            "UNR grid lookup of the frozen snapshot. Used for GNSS east/north only "
            "when the DISP-CAL products carry no gnss_ve/gnss_vn layers; the "
            "provenance hash must then match the one in DISP-CAL."
        ),
    )

    unr_timeseries_dir: OptionalPath = Field(
        default=None,
        description=(
            "Node files of the frozen UNR snapshot (nodes/ of "
            "unr_grid_<version>_<date>); see unr_grid_latlon_file."
        ),
    )

    model_config = STRICT_CONFIG_WITH_ALIASES


class DynamicAncillaryFileGroup(YamlModel):
    """Ancillary files that change from job to job."""

    algorithm_parameters_file: RequiredPath = Field(
        ...,
        description="Path to file containing SAS algorithm parameters (YAML).",
    )

    los_file_ascending: RequiredPath = Field(
        ...,
        description="DISP-S1-STATIC line_of_sight_enu of the ascending frame.",
    )

    los_file_descending: OptionalPath = Field(
        default=None,
        description=(
            "DISP-S1-STATIC line_of_sight_enu of the descending frame; required with "
            "descending inputs."
        ),
    )

    model_config = STRICT_CONFIG_WITH_ALIASES


class StaticAncillaryFileGroup(YamlModel):
    """Versioned, job-independent ancillary databases."""

    algorithm_parameters_overrides_json: OptionalPath = Field(
        default=None,
        description=(
            "JSON file of per-frame_id algorithm parameter overrides applied on top "
            'of the algorithm_parameters_file. Format: {"data": {"<frame_id>": '
            "{<option group>: {<option>: <value>}}}}."
        ),
    )

    defo_area_db_json: OptionalPath = Field(
        default=None,
        description=(
            "Venti deforming-area database (GeoJSON) DISP-CAL used; needed when "
            "gnss_options.exclude_defo_nodes is true."
        ),
    )

    gia_model_file: OptionalPath = Field(
        default=None,
        description=(
            "GIA vertical-rate model (ICE-6G_D) for the context layer; omitted -> no "
            "GIA context layer."
        ),
    )

    model_config = STRICT_CONFIG_WITH_ALIASES
