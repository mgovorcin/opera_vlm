"""CEOS Analysis Ready Data (CEOS-ARD) metadata: one registry, three sources.

Every CEOS field the product claims is declared once in `CEOS_FIELDS` with the
PFS section it answers, the product group it goes to, and where its value
comes from:

- ``static``   constant for the product type: `CEOS_STATIC` (generated from
               the interview spec; edit here afterwards).
- ``computed`` derived by `_computed` from the workflow and the product
               layers (granule count, bounding box, sample spacing...).
- ``runtime``  supplied by the algorithm in ``AlgorithmResult.ceos`` (orbit
               direction, incidence angles, satellites of this job...).

A job may override any declared value through ``AlgorithmResult.ceos`` (e.g.
``ceos_atmospheric_phase_correction`` only when troposphere files were
applied, or document identifiers inherited from the input product, as
cal-disp does). Undeclared names raise: add the field here first.

`check_compliance` reads a written product back and reports each field as
ok / missing / placeholder; ``opera-vlm ceos check`` exits 1 unless all required
fields are ok. ``opera-vlm ceos matrix`` renders docs/ceos-compliance.md
(regenerated by ``pixi run gen-configs``; CI fails on drift).

Section numbers follow the CEOS-ARD PFS for SAR v1.2 as annotated in DISP-S1;
verify them against the PFS of the product family you claim.
"""

