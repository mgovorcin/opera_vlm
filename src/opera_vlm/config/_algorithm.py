"""Algorithm parameters: the science knobs, kept out of the PGE runconfig.

The PGE passes a path to this YAML (dynamic_ancillary_file_group.
algorithm_parameters_file); per-frame values come from the static
algorithm_parameters_overrides_json and are merged by `with_overrides`.

GENERATED by sas-scaffold from the interview spec, then owned by this repo.
Every parameter has a default here; the committed
configs/algorithm_parameters.yaml is generated from these models
(`opera-vlm config algorithm`), and tests/test_configs.py fails when they drift.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any, List, Literal, Optional  # noqa: F401

from pydantic import Field

from ._utils import nested_update
from ._yaml import STRICT_CONFIG, YamlModel, _computed_fields_exclude

#: Option group that un-grouped override keys (``{"window": 3}``) apply to.
DEFAULT_OPTION_GROUP = "decomposition_options"


class DecompositionOptions(YamlModel):
    """LOS -> east/up (venti.decomposition)."""

    cond_max: float = Field(
        default=10.0,
        gt=1,
        description=(
            "Above this condition number of the weighted design the WLS solve is not "
            "trusted and the pixel is projected (mode 2)."
        ),
    )

    min_up: float = Field(
        default=0.1,
        gt=0,
        lt=1,
        description=(
            "Minimum |up| component of the look vector for the single-geometry "
            "projection."
        ),
    )

    sigma_disp_meters: float = Field(
        default=0.007,
        ge=0,
        description=(
            "Per-point DISP noise below the calibration cutoff (TS-S1: 3.9-6.8 mm on "
            "the four T38 frames, from 7 x 7 pixel medians, so a lower bound for one "
            "pixel); per-frame values in the static overrides file. Units: meters."
        ),
    )

    sigma_rate_meters_per_year: float = Field(
        default=0.0015,
        ge=0,
        description=(
            "Per-look error growing with the pair's span, added as (rate x years) in "
            "quadrature: chained per-pair calibration leaves a rate error at every "
            "pixel (T57, fitted on LA F16940 + F18904: 1.5 mm/yr). Units: meters/year."
        ),
    )

    model_config = STRICT_CONFIG


class InputOptions(YamlModel):
    """Which DISP pixels enter the run."""

    mask_layers: List[str] = Field(
        default_factory=lambda: ["water_mask"],
        description=(
            "DISP mask layers (True = valid) applied to every pair before chaining;"
            " a pixel masked in any pair of the chain is NaN. recommended_mask"
            " varies from pair to pair; water_mask is the safe default."
        ),
    )

    model_config = STRICT_CONFIG


class TemporalOptions(YamlModel):
    """Resampling asc and desc onto common epochs (venti.temporal)."""

    window_days: float = Field(
        default=96.0,
        gt=0,
        description="Full width of the moving window. Units: days.",
    )

    method: Literal["huber_linear", "theil_sen", "linear"] = Field(
        default="huber_linear",
        description="Robust line fit used in each window.",
    )

    min_points: int = Field(
        default=3,
        ge=2,
        description="Fewer epochs in a window give no value.",
    )

    target_spacing_days: float = Field(
        default=12.0,
        gt=0,
        description=(
            "Spacing of the target epochs over the span both geometries cover; the "
            "first target is the reference of every product. Units: days."
        ),
    )

    max_extrapolation_days: float = Field(
        default=0.0,
        ge=0,
        description=(
            "Targets farther than this outside a series are not produced. Units: days."
        ),
    )

    model_config = STRICT_CONFIG


class GnssOptions(YamlModel):
    """Horizontal GNSS used to fix north (and east in mode 2)."""

    horizontal_source: Literal["cal_product", "grid"] = Field(
        default="cal_product",
        description=(
            "cal_product: gnss_ve/gnss_vn layers of DISP-CAL; grid: sample the frozen "
            "UNR snapshot with Venti."
        ),
    )

    require_provenance_match: bool = Field(
        default=True,
        description=(
            "Fail unless every DISP-CAL product carries a GNSS provenance record and "
            "the realisation (grid version/type/frame, snapshot, lookup hash, buffer, "
            "defo-area DB version) matches it (venti.gnss.vlm.verify_provenance). "
            "False accepts products without a record (pre-T37.3) with a warning."
        ),
    )
    buffer_meters: float = Field(
        default=50_000.0,
        ge=0,
        description=(
            "Grid nodes this far outside the frame (R-G2). Must equal the DISP-CAL "
            "value: the provenance check fails otherwise."
        ),
    )
    exclude_defo_nodes: bool = Field(
        default=False,
        description=(
            "Drop grid nodes inside the curated defo areas (R-G5); as DISP-CAL."
        ),
    )
    reinterpolate_excluded: bool = Field(
        default=False,
        description="Re-estimate the excluded nodes with GPS Imaging; as DISP-CAL.",
    )

    model_config = STRICT_CONFIG


class ContextOptions(YamlModel):
    """Context layers: rigid plate motion and GIA (opera_vlm.context)."""

    plate: Optional[str] = Field(
        default=None,
        description=(
            "Plate of the plate_motion layers (ITRF2020-PMM name or UNR code: NA, PA,"
            " CA...). Null takes it from Venti's frame-parameter table."
        ),
    )

    plate_model: Literal["ITRF2020-PMM", "ITRF2014-PMM"] = Field(
        default="ITRF2020-PMM",
        description="Plate-motion model (geepers.euler).",
    )

    gia_variable: str = Field(
        default="Drad_250",
        description=(
            "Vertical-rate variable of the GIA model file (mm/yr); ICE-6G_D calls it"
            " Drad_250."
        ),
    )

    model_config = STRICT_CONFIG


class AlgorithmParameters(YamlModel):
    """OPERA Vertical Land Motion from DISP and DISP-CAL algorithm parameters."""

    input_options: InputOptions = Field(
        default_factory=InputOptions,
        description="Which DISP pixels enter the run.",
    )

    decomposition_options: DecompositionOptions = Field(
        default_factory=DecompositionOptions,
        description="LOS -> east/up (venti.decomposition).",
    )

    temporal_options: TemporalOptions = Field(
        default_factory=TemporalOptions,
        description="Resampling asc and desc onto common epochs (venti.temporal).",
    )

    gnss_options: GnssOptions = Field(
        default_factory=GnssOptions,
        description="Horizontal GNSS used to fix north (and east in mode 2).",
    )

    context_options: ContextOptions = Field(
        default_factory=ContextOptions,
        description="Context layers: rigid plate motion and GIA (opera_vlm.context).",
    )

    model_config = STRICT_CONFIG

    def with_overrides(self, overrides: Mapping[str, Any]) -> "AlgorithmParameters":
        """Return a validated copy with `overrides` deep-merged in.

        Keys are option groups (``{"group": {"option": 1}}``) or, as a
        shorthand, options of `DEFAULT_OPTION_GROUP`. Unknown keys raise
        (extra="forbid"), so a typo in an overrides file fails loudly
        instead of being ignored.
        """
        if not overrides:
            return self
        data = self.model_dump(exclude=_computed_fields_exclude(self))
        groups = set(type(self).model_fields)
        for key, value in overrides.items():
            if key in groups:
                nested_update(data, {key: value})
            else:
                nested_update(data[DEFAULT_OPTION_GROUP], {key: value})
        return type(self).model_validate(data)

    def to_yaml_str(self) -> str:
        """Return the parameters as YAML text (embedded in the product metadata)."""
        from io import StringIO

        buf = StringIO()
        self.to_yaml(buf, with_comments=False)
        return buf.getvalue()
