"""``opera-vlm stage``: download/prepare inputs for a job.

Staging is part of the CLI (not loose scripts) so it is versioned, tested and
shipped in the image with the SAS. It is never called by ``opera-vlm run``: the
SAS itself only reads local files listed in the runconfig, which keeps
operational runs hermetic. Network dependencies live in the ``stage`` extra
and are imported lazily.

GENERATED by sas-scaffold from the interview spec, then owned by this repo.
"""

from __future__ import annotations

from pathlib import Path

import click


@click.group(name="stage")
def stage_group() -> None:
    """Download and prepare input data (not used by `run`)."""


@stage_group.command(name="disp")
@click.option(
    "-o",
    "--output-dir",
    type=click.Path(path_type=Path),
    default=Path("staging"),
    show_default=True,
)
@click.option("--frame-id", type=int, required=True)
def disp_cli(output_dir: Path, frame_id: int) -> None:
    """Download DISP-S1 products for a frame and date range."""
    from opera_vlm.stage import stage_disp

    for path in stage_disp(output_dir, frame_id=frame_id):
        click.echo(path)


